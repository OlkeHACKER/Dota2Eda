function applyLanguage(language) {
  if (!interfaceText[language]) return;
  experienceLanguage = language;
  localStorage.setItem('foodexpress-language', language);
  document.documentElement.lang = language === 'kk' ? 'kk' : language;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const translation = text(element.dataset.i18n);
    if (typeof translation === 'string') element.textContent = translation;
  });
  if (!document.getElementById('cart-items').children.length) {
    document.getElementById('cart-message').textContent = text('cartEmpty');
  }
  if (!document.getElementById('restaurant-tabs').children.length) {
    document.getElementById('menu-message').textContent = text('loadingMenu');
  }
  window.setFoodLanguage?.(language);
  if (selectedRestaurant) renderRestaurantExperience(selectedRestaurant);
  if (selectedDish) renderDishExperience(selectedDish.dish, selectedDish.restaurant);
  document.getElementById('language-select').value = language;
}

document.getElementById('language-select').addEventListener('change', (event) => {
  applyLanguage(event.target.value);
});
